# Classes and objects are the two core concepts in object-oriented programming.
# A class defines what an object should look like, and an object is created based on that class

class myclass:   #to reate the class key word class is used and then the name of class
    x=2

c1=myclass()  #here c1 is the object of the class myclass
print(c1.x)   #here x is printed from the class myclass by an object c1

del c1       #here key word del delet the object c1